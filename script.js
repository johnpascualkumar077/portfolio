function setLang(lang) {
    document.getElementById('htmlRoot').lang = lang;
    document.getElementById('btnJa').classList.toggle('active', lang === 'ja');
    document.getElementById('btnEn').classList.toggle('active', lang === 'en');
    const t = i18n[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const k = el.dataset.i18n;
        if (t[k] !== undefined) el.innerHTML = t[k];
    });
    const n = document.getElementById('formName'), m = document.getElementById('formMsg');
    if (n) n.placeholder = t['_ph-name'];
    if (m) m.placeholder = t['_ph-msg'];
    localStorage.setItem('lang', lang);
}

// ── INITIALIZATION ──
document.addEventListener('DOMContentLoaded', () => {
    setLang(localStorage.getItem('lang') || 'ja');
    AOS.init({ once: true, duration: 800, offset: 80 });

    // Counter
    const obs = new IntersectionObserver(entries => {
        entries.forEach(e => {
            if (e.isIntersecting) {
                const el = e.target, target = +el.dataset.target;
                let cur = 0; const step = target / (1800 / 16);
                const t = setInterval(() => { cur = Math.min(cur + step, target); el.textContent = Math.floor(cur); if (cur >= target) clearInterval(t); }, 16);
                obs.unobserve(el);
            }
        });
    }, { threshold: 0.5 });
    document.querySelectorAll('.stat-number').forEach(c => obs.observe(c));

    // Back to Top
    const btt = document.getElementById('backToTop');
    window.addEventListener('scroll', () => btt.classList.toggle('show', window.scrollY > 300));
    btt.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));

    // Form
    document.querySelectorAll('.needs-validation').forEach(f => {
        f.addEventListener('submit', e => { if (!f.checkValidity()) { e.preventDefault(); e.stopPropagation(); } f.classList.add('was-validated'); });
    });

    // AI widget show/hide
    const aiToggle = document.getElementById('aiToggle');
    const aiWidget = document.getElementById('aiWidget');
    aiToggle.addEventListener('click', () => {
        aiWidget.classList.toggle('show');
        if (aiWidget.classList.contains('show')) startAiTyping();
    });
});

// ── WORK MODAL LOGIC ──
function openWorkModal(id) {
    const lang = document.getElementById('htmlRoot').lang;
    const t = i18n[lang];
    const item = workDetails[id];

    document.getElementById('modalTitle').innerHTML = t[item.titleKey];
    document.getElementById('modalProb').innerHTML = t[item.probKey];

    const techList = document.getElementById('modalTech');
    techList.innerHTML = '';
    t[item.techKey].split(', ').forEach(tech => {
        const span = document.createElement('span');
        span.className = 'tech-tag';
        span.style.background = 'var(--accent-light)';
        span.style.color = 'var(--accent)';
        span.innerHTML = tech;
        techList.appendChild(span);
    });

    document.getElementById('modalDur').innerHTML = t[item.durKey];

    const modal = new bootstrap.Modal(document.getElementById('workModal'));
    modal.show();
}

// ── AI TYPING SIMULATION ──
let aiTypingIdx = 0;
function startAiTyping() {
    const lang = document.getElementById('htmlRoot').lang;
    const t = i18n[lang];
    const messages = [t['ai-welcome'], t['ai-msg-1'], t['ai-msg-2'], t['ai-msg-3']];
    const container = document.getElementById('aiContent');
    container.innerHTML = '';

    let msgIdx = 0;
    function typeNextMsg() {
        if (msgIdx >= messages.length) return;
        const p = document.createElement('p');
        p.className = 'ai-typing mb-2';
        if (msgIdx > 0) p.style.color = 'var(--accent)';
        container.appendChild(p);

        let charIdx = 0;
        const text = messages[msgIdx];
        const timer = setInterval(() => {
            p.innerHTML += text[charIdx];
            charIdx++;
            if (charIdx >= text.length) {
                clearInterval(timer);
                msgIdx++;
                setTimeout(typeNextMsg, 600);
            }
        }, 30);
    }
    typeNextMsg();
}
